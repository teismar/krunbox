        ["kgx", "-e", f"ssh {target}"],
        # Freedesktop Terminal Execution Specification
        ["xdg-terminal-exec", "ssh", target],
        # Debian / Ubuntu alternative
        ["x-terminal-emulator", "-T", title, "-e", "ssh", target],
        ["x-terminal-emulator", "-e", "ssh", target],
        # Modern GPU & cross-platform terminals
        ["alacritty", "-T", title, "-e", "ssh", target],
